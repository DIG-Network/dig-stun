/// The strongest form of "byte-exact": a signature produced by a COMPLETELY INDEPENDENT
/// ECDSA-P256-SHA256 implementation (Python's `cryptography`, OpenSSL-backed, no shared code with
/// `ring`) verifies against this crate's own [`verify_signed_request`]. This proves the byte
/// layout `verify_signed_request` assumes (which 65 bytes are the point, which is R/S) is correct
/// against a real second implementation, not merely self-consistent with `ring`'s own signer.
#[test]
fn a_signature_from_an_independent_library_verifies() {
    let spki = independent_spki_der();
    let sig = independent_sig_der();
    let kind = RequestKind::Signed {
        spki: &spki,
        nonce: independent_nonce_wire(),
        signature: &sig,
    };
    let identity =
        verify_signed_request(&TXID, &kind).expect("an independently signed request must verify");
    assert_eq!(identity.spki_der(), &spki);
}

#[test]
fn verify_signed_request_rejects_a_tampered_nonce() {
    let spki = independent_spki_der();
    let sig = independent_sig_der();
    let mut tampered_nonce = independent_nonce_wire().to_vec();
    tampered_nonce[0] ^= 1; // flip one bit of the SIGNED preimage's nonce field
    let kind = RequestKind::Signed {
        spki: &spki,
        nonce: &tampered_nonce,
        signature: &sig,
    };
    assert_eq!(
        verify_signed_request(&TXID, &kind),
        Err(CredentialError::BadSignature)
    );
}

