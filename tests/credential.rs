/// Every error shape sent in reply to an already-credentialed request — challenge, stale,
/// malformed — is never larger than what triggered it (`SPEC.md` §14.3.3). The bare refusal is the
/// one exception: it answers an uncredentialed bare request, so there is no larger trigger to size
/// against; instead it is bounded to today's baseline STUN success ratio (2.2) rather than
/// exceeding it. The sizes below pair what a real server actually produces, taken directly from
/// the shapes table.
#[test]
fn error_shapes_never_exceed_their_trigger_except_bare_refusal_at_stun_baseline() {
    // Every size below comes from actually CALLING the real encoders (never a hand-typed
    // constant), so this test verifies the shipped byte layout rather than its own arithmetic.
    let spki = independent_spki_der();
    let bare_request = dig_stun::encode_binding_request(&TXID);
    let identity_request = encode_identity_request(&TXID, &spki);
    let (signer, _spki) = ring_test_signer();
    let signed_request = encode_signed_request(&TXID, independent_nonce_wire(), &signer);

    let raw_nonce = [0u8; NONCE_LEN];
    let bare_refusal = encode_challenge(&TXID, ERR_UNAUTHENTICATED, None);
    let challenge = encode_challenge(&TXID, ERR_UNAUTHENTICATED, Some(&raw_nonce));
    let stale = encode_challenge(&TXID, ERR_STALE_NONCE, Some(&raw_nonce));
    let malformed = encode_challenge(&TXID, ERR_BAD_REQUEST, None);

    // The bare refusal answers a 20-byte bare request at today's ordinary IPv6 success ratio
    // (44/20 = 2.2), never the larger 88-byte challenge shape.
    assert_eq!(bare_refusal.len() as f64 / bare_request.len() as f64, 2.2);
    // A challenge/malformed reply is only ever sent to a request carrying a 92-byte identity, so
    // it is always SMALLER than what triggered it.
    assert!(challenge.len() < identity_request.len());
    assert!(malformed.len() < identity_request.len());
    // A stale reply is only ever sent to a full signed request.
    assert!(stale.len() < signed_request.len());
}

/// Append one raw TLV attribute to an already-encoded message and fix up its length header —
/// deliberately NOT calling into the crate's own (`pub(super)`, unreachable from here) encoder, so
/// this integration test builds its fixture through a genuinely independent path.
fn append_extra_attribute(msg: &mut Vec<u8>, attr_type: u16, value: &[u8]) {
    let pad = (4 - (value.len() % 4)) % 4;
    msg.extend_from_slice(&attr_type.to_be_bytes());
    msg.extend_from_slice(&(value.len() as u16).to_be_bytes());
    msg.extend_from_slice(value);
    msg.extend(std::iter::repeat(0u8).take(pad));
    let added = (4 + value.len() + pad) as u16;
    let new_len = u16::from_be_bytes([msg[2], msg[3]]) + added;
    msg[2..4].copy_from_slice(&new_len.to_be_bytes());
}

