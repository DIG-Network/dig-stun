/// A small reference implementation of the RECOMMENDED server flow (`SPEC.md` §14.5's ordering),
/// counting how many times it reaches [`verify_signed_request`] — the conformance property is
/// that this is 0 for Stale/Invalid and 1 for Fresh (`SPEC.md` §11 item 12).
fn reference_server_decide(
    mode: CredentialMode,
    kind: &RequestKind<'_>,
    nonce_check: Option<NonceCheck>,
    txid: &TransactionId,
    verify_calls: &AtomicUsize,
) -> ServerDecision {
    let verified = match (kind, nonce_check) {
        (RequestKind::Signed { .. }, Some(NonceCheck::Fresh)) => {
            verify_calls.fetch_add(1, Ordering::SeqCst);
            Some(verify_signed_request(txid, kind))
        }
        _ => None,
    };
    decide(mode, kind, nonce_check, verified)
}

#[test]
fn verify_signed_request_is_not_invoked_for_stale_or_invalid_nonce_only_for_fresh() {
    let counter = AtomicUsize::new(0);
    let kind = RequestKind::Signed {
        spki: DUMMY,
        nonce: DUMMY,
        signature: DUMMY,
    };

    reference_server_decide(
        CredentialMode::Advisory,
        &kind,
        Some(NonceCheck::Invalid),
        &TXID,
        &counter,
    );
    assert_eq!(
        counter.load(Ordering::SeqCst),
        0,
        "an Invalid nonce must never reach verify_signed_request"
    );

    reference_server_decide(
        CredentialMode::Advisory,
        &kind,
        Some(NonceCheck::Stale),
        &TXID,
        &counter,
    );
    assert_eq!(
        counter.load(Ordering::SeqCst),
        0,
        "a Stale nonce must never reach verify_signed_request"
    );

    let (signer, _spki) = ring_test_signer();
    let msg = encode_signed_request(&TXID, independent_nonce_wire(), &signer);
    let (_, fresh_kind) = classify_request(&msg).unwrap();
    reference_server_decide(
        CredentialMode::Advisory,
        &fresh_kind,
        Some(NonceCheck::Fresh),
        &TXID,
        &counter,
    );
    assert_eq!(
        counter.load(Ordering::SeqCst),
        1,
        "a Fresh nonce must reach verify_signed_request exactly once"
    );
}

/// A P-256 signer backed by a freshly generated `ring` key pair — used everywhere a genuine,
/// working signature is needed (as opposed to the fixed independent-library vectors above, which
/// exist specifically to cross-check byte layout).
struct RingTestSigner {
    key_pair: ring::signature::EcdsaKeyPair,
    spki: Vec<u8>,
}

impl StunSigner for RingTestSigner {
    fn spki_der(&self) -> &[u8] {
        &self.spki
    }
    fn sign(&self, message: &[u8]) -> Vec<u8> {
        let rng = ring::rand::SystemRandom::new();
        self.key_pair
            .sign(&rng, message)
            .expect("ring signing must succeed")
            .as_ref()
            .to_vec()
    }
}

fn ring_test_signer() -> (RingTestSigner, Vec<u8>) {
    let rng = ring::rand::SystemRandom::new();
    let pkcs8 = ring::signature::EcdsaKeyPair::generate_pkcs8(
        &ring::signature::ECDSA_P256_SHA256_ASN1_SIGNING,
        &rng,
    )
    .expect("ring key generation must succeed");
    let key_pair = ring::signature::EcdsaKeyPair::from_pkcs8(
        &ring::signature::ECDSA_P256_SHA256_ASN1_SIGNING,
        pkcs8.as_ref(),
        &rng,
    )
    .expect("ring must load its own freshly generated pkcs8");
    let point = key_pair.public_key().as_ref().to_vec(); // 65 bytes: 0x04 || X || Y
    let mut spki = P256_SPKI_PREFIX.to_vec();
    spki.extend_from_slice(&point);
    let spki_clone = spki.clone();
    (RingTestSigner { key_pair, spki }, spki_clone)
}

