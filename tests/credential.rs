/// Round-trip a raw issued nonce through the crate's own public wire encode/decode functions to
/// get its base64url wire form — mirrors how a real caller only ever sees a nonce this way, never
/// as raw bytes, and avoids re-implementing a second base64url encoder in this test file.
fn wire_nonce(raw: &[u8; NONCE_LEN]) -> Vec<u8> {
    let txid = [9u8; 12];
    let msg = encode_challenge(&txid, ERR_UNAUTHENTICATED, Some(raw));
    parse_challenge(&msg, &txid).unwrap().nonce.unwrap()
}

#[test]
fn independent_hmac_matches_the_issued_nonce() {
    // Independently computed in Python (stdlib hmac/hashlib) for SECRET=00..1f, source
    // 203.0.113.7:51000, NOW=1_000_000_000.
    let secret: [u8; 32] = (0u8..32).collect::<Vec<_>>().try_into().unwrap();
    let issuer = NonceIssuer::from_secret(secret);
    let now: u64 = 1_000_000_000;
    let got = issuer.issue(source_a(), now);
    let want = hex_to_bytes("00 fe 50 2a e6 b3 5c 05 5e 6b 3d 13 7d 96 f7 c8 c6 97 6a 79");
    assert_eq!(
        got.to_vec(),
        want,
        "the HMAC preimage must byte-match an independent computation"
    );
}

